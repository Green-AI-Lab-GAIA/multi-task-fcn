def predict_network(ortho_image_shape: Tuple, 
                    dataloader: torch.utils.data.DataLoader, 
                    model: nn.Module,
                    num_classes: int,
                    crop_size: int,
                    input_dimension: Optional[int] = None,
                    activation_aux_layer: Literal["sigmoid", "relu", "gelu"] = "sigmoid",
                    debug_mode: bool = False):
    """
    It runs the inference of the entire image map.
    Get depth values and the probability of each class.
    
    Supports automatic resizing: if input_dimension != crop_size, the model output
    is resized back to crop_size before being placed in the reconstruction array.

    Parameters
    ----------
    ortho_image_shape : Tuple
        The shape of the orthoimage (channels, height, width)
    dataloader : torch.utils.data.DataLoader
        Torch dataloader with all the patches from the image to be evaluated
    model : nn.Module
        The model with the weight of the current iteration
    num_classes : int
        The number of classes in the segmentation
    crop_size : int
        The size of crops extracted from the image
    input_dimension : int, optional
        The size of input to the model. If different from crop_size, 
        outputs are resized back to crop_size.
    activation_aux_layer : str
        Activation function for auxiliary output

    Returns
    -------
    Tuple
        - pred_prob :  Probability of each class
        - The class with the highest probability value
        - pred_depth :  The depth_map generated by the model
    """
    if input_dimension is None:
        input_dimension = crop_size
    
    need_resize = (input_dimension != crop_size)
    
    pred_prob = np.zeros(shape=(ortho_image_shape[1], ortho_image_shape[2], num_classes), dtype='float16')
    pred_depth = np.zeros(shape=(ortho_image_shape[1], ortho_image_shape[2]), dtype='float16')
    count_image = np.zeros(shape=(ortho_image_shape[1], ortho_image_shape[2]), dtype='uint8')
    
    DEVICE = get_device()
    model.eval()
    
    if activation_aux_layer == "sigmoid":
        activation_aux_module = nn.Sigmoid()
    elif activation_aux_layer == "relu":
        activation_aux_module = nn.ReLU()
    elif activation_aux_layer == "gelu":
        activation_aux_module = nn.GELU()
    else:
        raise ValueError("Activation function not recognized")

    activation_aux_module = activation_aux_module.to(DEVICE)
    activation_main_layer = nn.Softmax(dim=1).to(DEVICE)
    
    with torch.no_grad(): 
        for i, (image, slices) in enumerate(tqdm(dataloader)):      
            # ============ forward pass ... ============
            input_batch = image.to(DEVICE, non_blocking=True, dtype=torch.float)
            
            out_pred = model(input_batch) 
            
            # Apply activation functions
            out_batch = activation_main_layer(out_pred['out'])  # (B, C, H, W)
            depth_out = activation_aux_module(out_pred['aux'])  # (B, 1, H, W)
            
            # Resize output back to crop_size if needed
            if need_resize:
                out_batch = F.interpolate(
                    out_batch,
                    size=(crop_size, crop_size),
                    mode='bilinear',
                    align_corners=False
                )
                depth_out = F.interpolate(
                    depth_out,
                    size=(crop_size, crop_size),
                    mode='bilinear',
                    align_corners=False
                )
            
            # Convert to numpy
            out_batch = out_batch.permute(0, 2, 3, 1)  # (B, H, W, C)
            out_batch = out_batch.data.cpu().numpy()
            depth_out = depth_out.data.cpu().numpy()
            
            batch_size, output_height, output_width, cl = out_batch.shape
            
            row_start, row_end, column_start, column_end = slices
            
            for b in range(batch_size):
                pred_prob[
                    row_start[b]:row_end[b],
                    column_start[b]:column_end[b]
                ] += out_batch[b]

                pred_depth[
                    row_start[b]:row_end[b],
                    column_start[b]:column_end[b]
                ] += depth_out[b][0]
                
                count_image[
                    row_start[b]:row_end[b],
                    column_start[b]:column_end[b]
                ] += 1

            if debug_mode and i > 2:
                break
                
        # Avoid zero division (and keep memory low).
        # NOTE: Do NOT use boolean masking here (pred_prob[mask] ...) because that
        # allocates large temporary arrays and can OOM on big rasters.
        count_image[count_image == 0] = 1

        logger.info("Dividing prob_map and depth_map by the number of times the pixel was predicted")
        # In-place division with broadcasting: no large temporaries.
        pred_prob /= count_image[..., None]
        pred_depth /= count_image
        
        del count_image
        return pred_prob, np.argmax(pred_prob, axis=-1).astype("uint8"), pred_depth


def evaluate_overlap(prediction_path: str,
                     overlap: float,
                     current_iter_folder: str,
                     ortho_image_shape: tuple,
                     args,
                     ortho_image_path: str = None,
                     save_compressed: bool = True,
):
    """This function runs an evaluation on the entire image.
    The image is divided into patches, that will be the inputs of the model.
    The overlap parameter sets overlap rate between each patch cut.
    
    Supports automatic resizing: patches are extracted at size_crops, resized to
    input_dimension for the model, and outputs are resized back to size_crops.

    Parameters
    ----------
    prediction_path : str
        Path to save predictions
    overlap : float
        Overlap rate between each patch
    current_iter_folder : str
        The path to the current iteration folder
    ortho_image_shape : tuple
        The shape the ortho image - Image from remote sensing (C, H, W)
    args : dict
        Arguments including size_crops, input_dimension, etc.
    ortho_image_path : str, optional
        Path to the orthoimage. If None, uses args.ortho_image (backwards compatible)
    """
    
    DEVICE = get_device()

    current_model_folder = join(current_iter_folder, args.model_dir)
    
    # Get input_dimension from args, default to size_crops if not specified
    input_dimension = getattr(args, 'input_dimension', args.size_crops)
    
    # Use provided ortho_image_path or fallback to args.ortho_image
    image_path = ortho_image_path if ortho_image_path is not None else args.ortho_image
    
    logger.info(f"Crop size: {args.size_crops}, Input dimension to model: {input_dimension}")
    logger.info(f"Evaluating image: {image_path}")

    test_dataset = DatasetForInference(
        image_path=image_path,
        crop_size=args.size_crops,
        overlap_rate=overlap,
        input_dimension=input_dimension
    )

    test_dataset.standardize_image_channels()

    test_loader = torch.utils.data.DataLoader(
            test_dataset,
            batch_size=args.batch_size * 6,
            num_workers=args.workers,
            pin_memory=True,
            drop_last=False,
            shuffle=False,
    )

    logger.info("Building data done with {} patches loaded.".format(test_dataset.coords.shape[0]))
    
    # Build model using the architecture specified in args
    model = build_model(
        in_channels=ortho_image_shape[0],
        num_classes=args.nb_class,
        arch=args.arch,
        dropout_rate=args.dropout_rate,
        batch_norm=args.batch_norm,
        pretrained=args.is_pretrained,
        psize=input_dimension,
    )

    last_checkpoint = join(current_model_folder, args.checkpoint_file)
    model = load_weights(model, last_checkpoint)
    logger.info(f"Model ({args.arch}) loaded from {last_checkpoint}")

    # Load model to GPU
    model = model.to(DEVICE)

    cudnn.benchmark = True

    prob_map, pred_class, depth_map = predict_network(
        ortho_image_shape=ortho_image_shape,
        dataloader=test_loader,
        model=model,
        num_classes=args.nb_class,
        crop_size=args.size_crops,
        input_dimension=input_dimension
    )

    logger.info("Converting predictions to uint8 type to save memory...")
    logger.info("Instead of prob and depth between 0 to 1, it will be between 0 to 255")
    prob_map = (prob_map*255).astype("uint8")
    depth_map = (depth_map*255).astype("uint8")
    
    gc.collect()
    
    logger.info(f"Saving prediction outputs..")

    if save_compressed:
        np.savez_compressed(
            prediction_path,
            prob_map=prob_map,
            pred_class=pred_class,
            depth_map=depth_map
        )

    else:
        np.savez(
            prediction_path,
            prob_map=prob_map,
            pred_class=pred_class,
            depth_map=depth_map
        )
    
    logger.info(f"Predictions saved on {prediction_path}")
    gc.collect()




def evaluate_iteration(current_iter_folder:str, args:dict):
    """Evaluate all regions to predict segmentation maps.
    Evaluate for many overlap values and save the results in the current_iter_folder/prediction folder.
    
    Supports multiple regions: evaluates each orthoimage and saves predictions
    in region-specific subfolders.

    Parameters
    ----------
    current_iter_folder : str
        Path to the current iteration folder.
    args : dict
        Dictionary of arguments (normalized with multi-region support).
    """
    num_regions = getattr(args, 'num_regions', 1)
    ortho_images = args.ortho_images
    
    logger.info(f"============ Initialized Evaluation for {num_regions} region(s) ============")
    
    for region_idx in range(num_regions):
        ortho_image_path = ortho_images[region_idx]
        
        # Create region-specific output folder
        if num_regions > 1:
            region_folder = join(current_iter_folder, f'region_{region_idx}')
            check_folder(region_folder)
            logger.info(f"=== Evaluating Region {region_idx}: {ortho_image_path} ===")
        else:
            region_folder = current_iter_folder
        
        ortho_image_metadata = get_image_metadata(ortho_image_path)
        ortho_image_shape = (ortho_image_metadata["count"], ortho_image_metadata["height"], ortho_image_metadata["width"])
        
        # Check if raster_prediction is done for this region
        raster_depth = join(region_folder, 'raster_prediction', f'depth_{sum(args.overlap)}.TIF') 
        raster_class_pred = join(region_folder, 'raster_prediction', f'join_class_{sum(args.overlap)}.TIF') 
        raster_prob = join(region_folder, 'raster_prediction', f'join_prob_{sum(args.overlap)}.TIF') 

        if exists(raster_depth) and exists(raster_class_pred) and exists(raster_prob):
            logger.info(f"Region {region_idx} evaluation already done. Skipping...")
            continue
        
        for overlap in args.overlap:
            prediction_path = join(region_folder, f'prediction_{overlap}.npz')
            
            is_prediction_overlap_done = exists(prediction_path)

            if is_prediction_overlap_done:
                logger.info(f"Region {region_idx}, Overlap {overlap} is already done. Skipping...")
                continue
            
            logger.info(f"Region {region_idx}, Overlap {overlap} is not done. Starting...")
            evaluate_overlap(
                prediction_path,
                overlap, 
                current_iter_folder,  # Model folder is always in main iter folder
                ortho_image_shape,
                args=args,
                ortho_image_path=ortho_image_path,
                save_compressed=False)
            
            logger.info(f"Region {region_idx}, Overlap {overlap} done.")

            gc.collect()
            torch.cuda.empty_cache()


